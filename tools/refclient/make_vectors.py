"""Writes docs/test-vectors.json: fixed inputs and the exact outputs the
protocol produces for them. The Dart apps' tests check they produce the
same bytes, so both sides provably speak the same protocol.

Run from the repo root:  python tools/refclient/make_vectors.py
"""
import base64
import hashlib
import json
import sys
from pathlib import Path

from nacl import bindings

sys.path.insert(0, str(Path(__file__).resolve().parent))
from comb_ref import KEYCHECK_PLAINTEXT, KEYCHECK_RECORD_ID, VaultKey, _aad, open_record  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]


def b64(data: bytes) -> str:
    return base64.b64encode(data).decode("ascii")


def sealed(key_bytes: bytes, nonce: bytes, aad: bytes, plaintext: bytes) -> bytes:
    return b"\x01" + nonce + bindings.crypto_aead_xchacha20poly1305_ietf_encrypt(plaintext, aad, nonce, key_bytes)


def main() -> None:
    key = VaultKey(bytes(range(32)))
    record_id = "AAECAwQFBgcICQoLDA0ODw"
    nonce = bytes(range(100, 124))
    payload = {"type": "file", "path": "Tasks/Send revised vault drawings.md", "content": "---\nid: t_1\n---\nഹലോ नमस्ते hello\n"}
    plaintext = json.dumps(payload, separators=(",", ":"), sort_keys=True, ensure_ascii=False).encode("utf-8")
    record_blob = sealed(key.record_key, nonce, _aad(b"record", record_id), plaintext)
    assert open_record(key, record_id, record_blob) == payload

    attachment = b"jpeg bytes \x00\xff"
    blob_nonce = bytes(range(200, 224))
    blob = sealed(key.blob_key, blob_nonce, _aad(b"blob", "v1"), attachment)

    keycheck_plain = json.dumps(KEYCHECK_PLAINTEXT, separators=(",", ":"), sort_keys=True).encode()
    keycheck_blob = sealed(key.record_key, bytes(24), _aad(b"record", KEYCHECK_RECORD_ID), keycheck_plain)

    vectors = {
        "note": "Generated by tools/refclient/make_vectors.py. Do not edit by hand.",
        "vault_key_b64": b64(key.raw),
        "record_key_b64": b64(key.record_key),
        "blob_key_b64": b64(key.blob_key),
        "recovery_key": key.recovery_key(),
        "record": {
            "record_id": record_id,
            "nonce_b64": b64(nonce),
            "plaintext_utf8": plaintext.decode("utf-8"),
            "blob_b64": b64(record_blob),
        },
        "attachment": {
            "nonce_b64": b64(blob_nonce),
            "plaintext_b64": b64(attachment),
            "blob_b64": b64(blob),
            "blob_id": hashlib.sha256(blob).hexdigest(),
        },
        "keycheck": {"record_id": KEYCHECK_RECORD_ID, "blob_b64": b64(keycheck_blob)},
        # Multi-block BLAKE2b, keyed and personalised, to check the long-message path.
        "blake2b_long_hex": hashlib.blake2b(
            b"a" * 300, digest_size=32, key=key.raw, person=b"comb-test-v1".ljust(16, b"\0")
        ).hexdigest(),
    }
    out = ROOT / "docs" / "test-vectors.json"
    out.write_text(json.dumps(vectors, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
